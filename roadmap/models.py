from django.db import models


class StudentProfile(models.Model):
    """The raw input a student submits through the form."""

    current_skills = models.TextField(
        help_text="Comma-separated list, e.g. 'Python, SQL'"
    )
    education = models.CharField(max_length=255)
    interests = models.TextField(
        help_text="Comma-separated list, e.g. 'Data, Automation'"
    )
    target_job = models.CharField(max_length=255)
    created_at = models.DateTimeField(auto_now_add=True)

    def skills_list(self):
        return [s.strip() for s in self.current_skills.split(",") if s.strip()]

    def interests_list(self):
        return [i.strip() for i in self.interests.split(",") if i.strip()]

    def __str__(self):
        return f"{self.target_job} candidate ({self.current_skills})"


class Roadmap(models.Model):
    """A generated roadmap tied to one profile submission."""

    SOURCE_CHOICES = [
        ("llm", "Generated by LLM (Ollama)"),
        ("rules", "Generated by rule-based fallback"),
    ]

    profile = models.ForeignKey(
        StudentProfile, on_delete=models.CASCADE, related_name="roadmaps"
    )
    source = models.CharField(max_length=10, choices=SOURCE_CHOICES, default="rules")
    raw_llm_response = models.TextField(blank=True, default="")
    created_at = models.DateTimeField(auto_now_add=True)

    def __str__(self):
        return f"Roadmap #{self.pk} for {self.profile.target_job}"


class RoadmapStep(models.Model):
    """A single ordered node in the roadmap (rendered as boxes with arrows)."""

    roadmap = models.ForeignKey(
        Roadmap, on_delete=models.CASCADE, related_name="steps"
    )
    order = models.PositiveIntegerField()
    title = models.CharField(max_length=255)
    description = models.TextField(blank=True, default="")

    class Meta:
        ordering = ["order"]

    def __str__(self):
        return f"{self.order}. {self.title}"
